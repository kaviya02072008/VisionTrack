import cv2
import time
from collections import deque

class PersonTracker:
    def __init__(self, max_history=50):
        """
        Maintains tracking history and metadata using IDs generated by YOLOv8 ByteTrack.
        max_history limits the trail length for drawing.
        """
        self.trajectories = {}  # track_id -> deque of (center_x, center_y)
        self.last_seen = {}     # track_id -> frame_count (for cleanup)
        self.max_history = max_history
        self.frame_count = 0

    def reset(self):
        """Clear all trajectory history and counters."""
        self.trajectories.clear()
        self.last_seen.clear()
        self.frame_count = 0

    def update(self, detections, frame):
        """
        Update the tracker history using the tracked detections.
        detections: list of dicts from PersonDetector (contains track_id)
        Returns:
            list of tracked objects formatted as requested
        """
        self.frame_count += 1
        current_time = time.time()
        tracked_objects = []
        
        for det in detections:
            track_id = det.get("track_id")
            
            # Skip if YOLO wasn't able to assign a tracking ID
            if track_id is None:
                continue
                
            track_id_str = str(track_id)
            
            center_x = det["center_x"]
            center_y = det["center_y"]
            
            # Initialize or update trajectory history
            if track_id_str not in self.trajectories:
                self.trajectories[track_id_str] = deque(maxlen=self.max_history)
                
            self.trajectories[track_id_str].append((center_x, center_y))
            self.last_seen[track_id_str] = self.frame_count
            
            # Format exactly as requested
            obj = dict(det)
            obj["track_id"] = track_id_str
            obj["frame_number"] = self.frame_count
            obj["timestamp"] = current_time
            tracked_objects.append(obj)
            
        # Clean up stale trajectories to prevent memory leaks (keep for ~100 frames)
        stale_ids = [tid for tid, last_frame in self.last_seen.items() if self.frame_count - last_frame > 100]
        for tid in stale_ids:
            self.trajectories.pop(tid, None)
            self.last_seen.pop(tid, None)
            
        return tracked_objects

    def draw_tracking(self, frame, tracked_objects):
        """
        Draw bounding boxes, tracking IDs, and movement trails on the frame.
        """
        for obj in tracked_objects:
            x1, y1 = obj["x1"], obj["y1"]
            x2, y2 = obj["x2"], obj["y2"]
            track_id = obj["track_id"]
            
            # Draw bounding box (Yellow)
            color = (0, 255, 255)
            cv2.rectangle(frame, (x1, y1), (x2, y2), color, 2)
            
            # Display ID
            label = f"ID {track_id}"
            (w, h), _ = cv2.getTextSize(label, cv2.FONT_HERSHEY_SIMPLEX, 0.6, 2)
            label_y = max(y1, 25)
            cv2.rectangle(frame, (x1, label_y - 25), (x1 + w, label_y), color, -1)
            cv2.putText(frame, label, (x1, label_y - 5), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (0, 0, 0), 2)
            
            # Draw movement trail
            if track_id in self.trajectories:
                trail = list(self.trajectories[track_id])
                for i in range(1, len(trail)):
                    pt1 = trail[i - 1]
                    pt2 = trail[i]
                    # Draw pink lines for the path
                    cv2.line(frame, pt1, pt2, (255, 0, 255), 2)
                    
        return frame
